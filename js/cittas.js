/* ==========================================================================
   cittas.js — සිත් වර්ග, the eighty-nine

   The Abhidhamma classification of consciousness. The point this board is
   built to make: the 89 are not a list anyone memorised item by item. They
   are generated by a small set of fields, most of them binary — which makes
   the whole thing a bit-field, and makes the count fall out of the fields
   rather than being asserted.

   Source layer: Abhidhammattha Saṅgaha, the standard Theravāda manual. Not
   the suttas. The micro board says the same thing about its own material.
   ========================================================================== */

