export function wireCittas(el) {
  const mods = [...el.querySelectorAll(".ct-mod")];
  const fieldsEl = el.querySelector("[data-fields]");
  const out = el.querySelector("[data-out]");
  let mode = "lobha";
  const bits = { feeling: 0, view: 0, prompt: 0 };

  const p = {
    name: el.querySelector("[data-pname]"),
    pali: el.querySelector("[data-ppali]"),
    si: el.querySelector("[data-psi]"),
    sys: el.querySelector("[data-psys]"),
    role: el.querySelector("[data-prole]"),
    note: el.querySelector("[data-pnote]"),
    ex: el.querySelector("[data-pex]"),
    link: el.querySelector("[data-plink]"),
  };

  function paint(o) {
    p.name.textContent = o.label;
    p.pali.textContent = o.pali;
    p.si.textContent = o.si;
    p.sys.textContent = o.sys;
    p.role.textContent = o.role;
    p.note.textContent = o.note;
    p.ex.innerHTML = (o.ex || []).map((e) => `<li>${e}</li>`).join("");
    p.link.href = `#/${o.ch}`;
    p.link.textContent = o.link || "Read the chapter →";
  }

  mods.forEach((m) => {
    const act = () => {
      mods.forEach((n) => n.classList.toggle("is-sel", n === m));
      const s = SPHERES.find((x) => x.id === m.dataset.sphere);
      const k = KAMA.find((x) => x.id === m.dataset.kama);
      if (s) {
        paint({
          label: s.label, pali: s.pali, si: s.si, sys: `${s.n} types`,
          role: s.d, note: "One of the four spheres. Every citta belongs to exactly one.",
          ex: [], ch: "cittas", link: "Read the chapter →",
        });
      } else if (k) {
        paint({
          label: k.label, pali: k.pali, si: k.si, sys: `${k.n} of the 54`,
          role: k.d,
          note: `Breaks into ${k.parts.map(([pp, , n]) => `${n} ${pp}`).join(", ")}.`,
          ex: k.parts.map(([pp, si, n, d]) => `<b>${n} ${pp}</b> <i>${si}</i> — ${d}`),
          ch: "cittas", link: "Read the chapter →",
        });
      }
    };
    m.addEventListener("click", act);
    m.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); act(); }
    });
  });

  function renderFields() {
    const d = DECODERS[mode];
    fieldsEl.innerHTML = d.fields
      .map(
        (f) => `
        <div class="decoder__field">
          <span class="decoder__flabel">${f.label} <i>${f.si}</i></span>
          <div class="decoder__opts" role="group" aria-label="${f.label}">
            ${f.opts
              .map(
                (o, i) => `
              <button class="decoder__opt${bits[f.key] === i ? " is-on" : ""}"
                      data-field="${f.key}" data-val="${i}">
                <span class="decoder__optpali">${o[0]}</span>
                <span class="decoder__optsi">${o[1]}</span>
                <span class="decoder__optplain">${o[2]}</span>
              </button>`
              )
              .join("")}
          </div>
        </div>`
      )
      .join("");

    fieldsEl.querySelectorAll(".decoder__opt").forEach((b) => {
      b.addEventListener("click", () => {
        bits[b.dataset.field] = Number(b.dataset.val);
        renderFields();
        renderOut();
      });
    });
  }

  function renderOut() {
    const d = DECODERS[mode];
    const r = decode(mode, bits);
    out.innerHTML = `
      <div class="decoder__num">citta ${r.i + 1} <span>of 8 · ${d.pali}</span></div>
      <div class="decoder__name">${r.name}</div>
      <div class="decoder__si">${r.si}</div>
      <div class="decoder__plain">${r.plain}</div>
      <div class="decoder__ex">${r.ex}</div>
      <div class="decoder__note">${d.note}</div>`;
  }

  el.querySelectorAll("[data-mode]").forEach((b) => {
    b.addEventListener("click", () => {
      mode = b.dataset.mode;
      el.querySelectorAll("[data-mode]").forEach((x) =>
        x.classList.toggle("is-on", x === b)
      );
      renderFields();
      renderOut();
    });
  });

  renderFields();
  renderOut();
  paint(DEFAULT_PANEL);

  void MOTION;
  void iconAt;
}
