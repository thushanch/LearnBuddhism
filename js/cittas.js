/* The standard ordering: feeling is the high bit, then view, then prompting. */
export function decode(mode, bits) {
  const i = bits.feeling * 4 + bits.view * 2 + bits.prompt;
  const d = DECODERS[mode];
  const name = d.fields
    .map((f) => f.opts[bits[f.key]][0])
    .join(" ");
  const si = d.fields.map((f) => f.opts[bits[f.key]][1]).join(" · ");
  const plain = d.fields.map((f) => f.opts[bits[f.key]][2]).join(", ");
  return { i, name, si, plain, ex: d.ex[i] };
}

